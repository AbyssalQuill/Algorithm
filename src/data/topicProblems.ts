/** 一个专题的课后练习，由易到难；没有专门配置时，用各道例题自己带的题目 */
export function topicProblems(id: string, fallback: Problem[] = []): Problem[] {
  const ids = TOPIC[id]
  const list = ids ? pickProblems(...ids) : fallback
  return [...list].sort((a, b) => (a.diff ?? 0) - (b.diff ?? 0))
}
